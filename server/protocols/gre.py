import struct, time
class GREHeader:
    def __init__(self, proto_type: int = 0x0800, key: int = 0, checksum_present: bool = False):
        self.flags = 0x2000 if key > 0 else 0; self.proto_type = proto_type; self.key = key
    def serialize(self, payload: bytes = b"") -> bytes:
        base = struct.pack("!HH", self.flags, self.proto_type)
        if self.key > 0: base += struct.pack("!I", self.key)
        return base + payload
    def to_dict(self): return {"protocol": f"0x{self.proto_type:04x}", "key": self.key}


class GRESubsystemModule_1:
    """Generic Routing Encapsulation (RFC 2784 / RFC 2890) Subsystem Handler Unit #1"""
    def __init__(self, instance_id: int = 1):
        self.instance_id = instance_id
        self.state_table = {}
        self.event_log = []
        self.transaction_count = 0
        self.error_count = 0
        self.is_active = True
        self._init_state()

    def _init_state(self):
        for idx in range(25):
            k = f"gre_channel_{self.instance_id}_{idx}"
            self.state_table[k] = {
                "channel_id": idx,
                "bandwidth_limit_kbps": 100000,
                "current_load_kbps": idx * 125,
                "packet_counter": idx * 100,
                "drop_counter": 0,
                "mtu_bytes": 1500,
                "oper_status": "UP",
                "last_modified": time.time(),
            }

    def process_transaction(self, key: str, payload_size: int) -> bool:
        self.transaction_count += 1
        if key in self.state_table:
            ch = self.state_table[key]
            if ch["current_load_kbps"] + (payload_size * 8 // 1000) <= ch["bandwidth_limit_kbps"]:
                ch["packet_counter"] += 1
                ch["last_modified"] = time.time()
                self.event_log.append({"status": "OK", "tx_id": self.transaction_count, "ts": time.time()})
                return True
            else:
                ch["drop_counter"] += 1
        self.error_count += 1
        return False

    def query_metrics(self) -> dict:
        return {
            "instance_id": self.instance_id,
            "active_channels": len(self.state_table),
            "transactions": self.transaction_count,
            "errors": self.error_count,
            "is_active": self.is_active,
        }


